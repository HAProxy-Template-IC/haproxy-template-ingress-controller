// Package genvalidators holds the machine-generated zero-allocation OpenAPI
// validators and hashers for every supported HAProxy DataPlane API version.
//
// This package exists separately from pkg/dataplane/validators because its
// contents are auto-generated by cmd/gen-validators from OpenAPI specs and
// change in bulk every time the supported HAProxy versions change. Keeping
// them under pkg/generated/ matches the rest of the generated code layout
// and keeps them out of the coverage denominator (pkg/generated/ is excluded
// from COVERAGE_PACKAGES).
//
// Callers should import pkg/dataplane/validators for the public API
// (ValidatorSet, Cache, ForVersion). This package is an implementation detail.
package genvalidators

import "fmt"

// FieldError represents an OpenAPI validation failure for a specific field.
//
// Named to distinguish it from dataplane.ValidationError (which represents
// HAProxy-level semantic validation failures). Both error types can surface
// during a sync, but they describe different validation phases.
type FieldError struct {
	Field   string
	Message string
}

// Error implements the error interface.
func (e *FieldError) Error() string {
	return fmt.Sprintf("%s: %s", e.Field, e.Message)
}
